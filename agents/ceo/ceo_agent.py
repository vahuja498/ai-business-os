import uuid
from datetime import datetime, timezone
from typing import Any
from agents.core.base_agent import BaseAgent
from agents.core.models import AgentMetadata, AgentRunRecord
from agents.research.research_agent import ResearchAgent
from agents.risk.risk_agent import RiskAgent
from policies.autonomy import AutonomyLevel
from policies.risk_rules import RiskLevel


class CEOAgent(BaseAgent):
    def __init__(self, model_provider=None, research_agent: ResearchAgent | None = None, risk_agent: RiskAgent | None = None):
        metadata = AgentMetadata(
            name="CEOAgent",
            description="Autonomous business orchestrator: decomposes goals, assigns specialist tasks, and requests approvals.",
            capabilities=["strategic_orchestration", "goal_decomposition", "agent_delegation", "kpi_monitoring"],
            allowed_tools=["database", "analytics"],  # CEO does not have direct unrestricted access
            system_policy="Operate transparently, enforce risk gating, delegate to specialists, never bypass approvals.",
            risk_level=RiskLevel.MEDIUM,
            autonomy_level=AutonomyLevel.LEVEL_1_ASSIST,
        )
        super().__init__(metadata=metadata, model_provider=model_provider)
        self.research_agent = research_agent or ResearchAgent(model_provider)
        self.risk_agent = risk_agent or RiskAgent(model_provider)

    async def run(
        self,
        input_data: dict[str, Any],
        business_id: str | None = None,
        task_id: str | None = None,
    ) -> AgentRunRecord:
        record = AgentRunRecord(
            agent_id=self.agent_id,
            business_id=business_id,
            task_id=task_id,
            input_data=input_data,
        )

        objective = input_data.get("objective", "Evaluate market opportunity")
        record.actions.append(f"CEO received strategic objective: '{objective}'")

        # Step 1: Goal Decomposition
        subtask_research_id = str(uuid.uuid4())
        subtask_risk_id = str(uuid.uuid4())
        decomposed_tasks = [
            {
                "task_id": subtask_research_id,
                "title": "Conduct market discovery and opportunity modeling",
                "assigned_agent": self.research_agent.name,
                "status": "IN_PROGRESS",
            },
            {
                "task_id": subtask_risk_id,
                "title": "Evaluate compliance, financial limits, and risk level",
                "assigned_agent": self.risk_agent.name,
                "status": "PENDING",
            },
        ]
        record.actions.append("Decomposed objective into research and risk evaluation tasks.")

        # Step 2: Delegate to Research Agent
        research_run = await self.research_agent.run(
            input_data={"objective": objective},
            business_id=business_id,
            task_id=subtask_research_id,
        )
        decomposed_tasks[0]["status"] = research_run.final_status
        record.actions.append(f"Research Agent completed execution with status: {research_run.final_status}")

        if research_run.final_status != "SUCCESS":
            record.errors.extend(research_run.errors)
            record.final_status = "FAILED"
            record.completed_at = datetime.now(timezone.utc)
            return record

        opportunity = research_run.outputs.get("opportunity", {})
        budget = opportunity.get("recommended_experiment", {}).get("budget", 500.0)

        # Step 3: Delegate to Risk Agent for Compliance & Approval Gating
        decomposed_tasks[1]["status"] = "IN_PROGRESS"
        risk_run = await self.risk_agent.run(
            input_data={
                "action_type": "launch_experiment",
                "description": f"Allocate {budget} INR budget for initial market validation experiment of: {opportunity.get('title')}",
                "amount": budget,
                "evidence": opportunity.get("evidence", []),
            },
            business_id=business_id,
            task_id=subtask_risk_id,
        )
        decomposed_tasks[1]["status"] = risk_run.final_status
        record.actions.append(f"Risk Agent completed evaluation with status: {risk_run.final_status}")

        if risk_run.final_status != "SUCCESS":
            record.errors.extend(risk_run.errors)
            record.final_status = "FAILED"
            record.completed_at = datetime.now(timezone.utc)
            return record

        # Forward approval requests generated by Risk Agent
        record.approval_requests.extend(risk_run.approval_requests)

        # Update opportunity status based on approval requirement
        if record.approval_requests:
            opportunity["status"] = "PENDING_APPROVAL"
            record.final_status = "PENDING_APPROVAL"
            record.actions.append("Generated pending approval request for CEO action.")
        else:
            opportunity["status"] = "APPROVED"
            record.final_status = "SUCCESS"

        record.outputs = {
            "objective": objective,
            "tasks": decomposed_tasks,
            "opportunity": opportunity,
            "risk_evaluation": risk_run.outputs.get("risk_evaluation"),
            "approval_requests": record.approval_requests,
        }
        record.completed_at = datetime.now(timezone.utc)
        return record
